import assert from 'node:assert/strict';
import {workstationProductIds} from '../src/production/workstationDefaults.mjs';
import {selectProducts,dailyProducts,selectLiveProducts} from '../src/production/multi.mjs';
import {selectPartEntries,partEntries} from '../src/production/partEntries.mjs';
import {scopeCapture} from '../src/production/parameters.mjs';
const items=[{id:'a',active:true,category:'FG',part_number:'PN-A'},{id:'b',active:true,category:'FG',part_number:'PN-B'},{id:'c',active:true,category:'SEMI',part_number:'PN-C'},{id:'raw',active:true,category:'RAW',part_number:'RAW-1'},{id:'off',active:false,category:'FG',part_number:'OFF'}];
const station={code:'M1',machine_type:'Assembly',active:true,materials:[{item_id:'a'},{item_id:'b'},{item_id:'a'},{item_id:'raw'},{item_id:'off'},{item_id:'missing'},{client_part_number:' pn-c '}]};
assert.deepEqual(workstationProductIds(station,items),['a','b','c']);
assert.deepEqual(workstationProductIds(station,items,['RAW']),['raw']);
assert.deepEqual(workstationProductIds({...station,materials:[{item_ids:['a','b']}]},items),['a','b']);
assert.deepEqual(workstationProductIds(null,items),[]);
assert.deepEqual(workstationProductIds({materials:[]},items,['FG'],['b']),['b'],'A machine without assignments preserves manual selections');
assert.deepEqual(workstationProductIds({...station,active:false},items),[]);
let sequence=0;const newId=()=>String(++sequence);
let daily=selectProducts({id:'report',item_id:'',products:[]},workstationProductIds(station,items),newId);
daily={...daily,machine_quantity:'15'};
daily=selectProducts(daily,['a','c'],newId);
assert.deepEqual(dailyProducts(daily).map(p=>p.item_id),['a','c']);
assert.equal(dailyProducts(daily)[0].machine_quantity,'15');
let partial=selectLiveProducts({item_id:'',quantity:'',products:[]},['a','b'],newId);
partial=selectLiveProducts(partial,['a','c'],newId);
assert.deepEqual(partial.products.map(p=>p.item_id),['a','c']);
let load=selectPartEntries({item_id:'',quantity:''},workstationProductIds(station,items,['RAW']),newId);
load={...load,quantity:'100'};load=selectPartEntries(load,['raw'],newId);
assert.equal(partEntries(load)[0].quantity,'100');
const template={id:'tpl',version:1,name:'Assembly',active:true,machine_types:['Assembly'],fields:[]};
let capture=scopeCapture({station_code:'',item_ids:[],values:{}},{station_code:'M1',item_ids:['a','b']},[template],[station]);
assert.equal(capture.template.id,'tpl');capture.values={pressure:{value:'10'}};
capture=scopeCapture(capture,{item_ids:['a','c']},[template],[station]);
assert.equal(capture.values.pressure.value,'10','Manual product selection retains compatible machine readings');
console.log('PASS: assignment defaults, deduplication, RAW/FG/SEMI eligibility, inactive/missing products, legacy part links, manual additions/removals and entered values');
