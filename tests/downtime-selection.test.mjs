import assert from 'node:assert/strict';
import {affectedIds,selectedDowntime,applySelectedDowntime} from '../src/production/downtimeSelection.mjs';
import {liveEditor,liveSubmission} from '../src/production/liveEditor.mjs';
import {downtimeTypeLabel} from '../src/production/breaks.mjs';
import {dailyProducts,switchProduct} from '../src/production/multi.mjs';
import {normalizeCapture} from '../src/production/capture.mjs';
const a={id:'a',session_id:'s',item_id:'A',station_code:'M',started_at:new Date(2026,9,15,6).toISOString(),shift_hours:8},b={...a,id:'b',item_id:'B'};
let n=0,edit=liveEditor(a,'checkpoint',[a,b],()=>String(++n));
assert.deepEqual(affectedIds(edit),['A','B']);
const stop={type:'breakdown',start_time:'08:00',end_time:'08:10',note:'new'};
edit=applySelectedDowntime(edit,[stop]);
assert.deepEqual(edit.products.map(p=>p.downtime_events.length),[1,1]);
edit={...edit,downtime_item_ids:['A']};
edit=applySelectedDowntime(edit,[...selectedDowntime(edit),{...stop,start_time:'09:00',end_time:'09:15',note:'A only'}]);
assert.deepEqual(edit.products.map(p=>p.downtime_events.length),[2,1]);
edit={...edit,downtime_item_ids:['A','B']};
edit=applySelectedDowntime(edit,selectedDowntime(edit).map(e=>e.note==='new'?{...e,note:'updated'}:e));
assert.equal(edit.products[0].downtime_events[0].note,'updated');assert.equal(edit.products[1].downtime_events[0].note,'updated');
assert.deepEqual(edit.products.map(p=>p.downtime_events.length),[2,1],'Independent history must not spread to siblings');
edit={...edit,downtime_item_ids:['B']};edit=applySelectedDowntime(edit,[]);
assert.deepEqual(edit.products.map(p=>p.downtime_events.length),[2,0]);
edit={...edit,downtime_item_ids:[]};assert.equal(applySelectedDowntime(edit,[stop]),edit);
edit.products.forEach(p=>p.quantity='100');
const payload=liveSubmission(edit,new Date(2026,9,15,12));assert.equal(payload.action,'checkpoint_batch');
assert.deepEqual(payload.payload.products.map(p=>p.downtime_events.length),[2,0]);
assert.ok(!JSON.stringify(payload).includes('_downtime_key'));
let daily={item_id:'A',start_time:'06:00',end_time:'14:00',products:[{item_id:'A',downtime_events:[stop]},{item_id:'B',downtime_events:[]}],downtime_events:[stop]};
assert.deepEqual(affectedIds(daily,dailyProducts(daily)),['A','B']);
daily=applySelectedDowntime(daily,[...selectedDowntime(daily,dailyProducts(daily)),{...stop,start_time:'10:00',end_time:'10:30'}],dailyProducts(daily));
assert.deepEqual(dailyProducts(daily).map(p=>p.downtime_events.length),[2,1]);
daily=switchProduct(daily,'B');assert.equal(daily.downtime_events.length,1);
assert.ok(!JSON.stringify(normalizeCapture(daily).downtime_events).includes('_downtime_key'));
const t=key=>key,settings={break_minutes:15,lunch_minutes:30};
assert.equal(downtimeTypeLabel('break',t,settings),'pr_downtime_break (15 min)');
assert.equal(downtimeTypeLabel('lunch',t,settings),'pr_downtime_lunch (30 min)');
assert.equal(downtimeTypeLabel('break',t,settings,{type:'break',auto_minutes:20}),'pr_downtime_break (20 min)');
console.log('PASS default all products, subsets, independent histories, edits, deletion, daily capture and inline break durations');
