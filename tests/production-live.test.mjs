import assert from 'node:assert/strict';
import {localStart,localDate,dayRange,liveKpis} from '../src/production/live.mjs';
assert.equal(localStart('2026-02-30','08:00'),null);
assert.equal(localStart('2026-10-08','25:00'),null);
assert.equal(localStart('2026-10-08','8:00'),null);
assert.equal(new Date(localStart('2026-10-08','08:00')).getHours(),8);
assert.equal(localDate(new Date(2026,9,8,23,30)),'2026-10-08');
assert.equal(dayRange('2026-02-30'),null);
const range=dayRange('2026-10-08');assert.equal(new Date(range.p_from).getHours(),0);assert.equal(localDate(range.p_to),'2026-10-09');
const run={started_at:'2026-10-08T08:00:00Z',latest_at:'2026-10-08T10:00:00Z',latest_quantity:150,expected_quantity:200,attainment:75,critical_percent:75,warning_percent:90};
assert.equal(liveKpis(run).performance,'warning');assert.equal(liveKpis({...run,attainment:74.9}).performance,'critical');assert.equal(liveKpis({...run,attainment:90}).performance,'on_track');
assert.equal(liveKpis(run).gap,50);assert.equal(liveKpis(run).rate,75);
assert.equal(liveKpis({...run,latest_quantity:210}).gap,0);
const historical=liveKpis({...run,period_quantity:100,period_at:'2026-10-08T09:00:00Z'});assert.equal(historical.quantity,100);assert.equal(historical.rate,100);
const empty=liveKpis({...run,period_quantity:null,period_at:null});assert.equal(empty.quantity,0);assert.equal(empty.performance,'pending');
console.log('PASS: local date ranges, invalid dates/times, percentage colors, historical quantities and no future-data leakage');
